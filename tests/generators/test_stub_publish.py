"""`stub:publish` and app-stub preference (T-51 "How it works": "Publishing stubs for
customisation ... Laravel's stub:publish" -- the task brief asked for it now rather than
deferring it, see the build report)."""

from __future__ import annotations

from pathlib import Path

from click.testing import CliRunner

from fastogram.console.commands.make import STUBS_DIR


def test_stub_publish_copies_every_bundled_stub(cli_group, runner: CliRunner, console_app_dir: Path) -> None:
    result = runner.invoke(cli_group, ["stub:publish"])
    assert result.exit_code == 0, result.output

    target_dir = console_app_dir / "stubs"
    bundled_names = {p.name for p in STUBS_DIR.glob("*.stub")}
    published_names = {p.name for p in target_dir.glob("*.stub")}
    assert bundled_names == published_names
    assert "Published" in result.output


def test_stub_publish_skips_existing_without_force(cli_group, runner: CliRunner, console_app_dir: Path) -> None:
    runner.invoke(cli_group, ["stub:publish"])
    custom = console_app_dir / "stubs" / "request.stub"
    custom.write_text("# custom\n{{ content }}\n")

    result = runner.invoke(cli_group, ["stub:publish"])
    assert result.exit_code == 0
    assert "Skipped" in result.output
    assert custom.read_text().startswith("# custom")


def test_stub_publish_force_overwrites(cli_group, runner: CliRunner, console_app_dir: Path) -> None:
    runner.invoke(cli_group, ["stub:publish"])
    custom = console_app_dir / "stubs" / "request.stub"
    custom.write_text("# custom\n{{ content }}\n")

    result = runner.invoke(cli_group, ["stub:publish", "--force"])
    assert result.exit_code == 0
    assert not custom.read_text().startswith("# custom")


def test_generator_prefers_the_app_stub_once_published(cli_group, runner: CliRunner, console_app_dir: Path) -> None:
    runner.invoke(cli_group, ["stub:publish"])
    app_stub = console_app_dir / "stubs" / "request.stub"
    app_stub.write_text("# Generated by our own custom stub.\n{{ content }}\n")

    result = runner.invoke(cli_group, ["make:request", "StorePostRequest"])
    assert result.exit_code == 0, result.output

    content = (console_app_dir / "app" / "http" / "requests" / "store_post_request.py").read_text()
    assert content.startswith("# Generated by our own custom stub.")
    assert "class StorePostRequest(FormRequest):" in content
